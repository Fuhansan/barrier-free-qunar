package com.qunar.barrier_free_qunar.java.sdk.model.coordinate;

/**
 * 手势左边实体类
 */
public class Point {

    private float x;

    private float y;

    public Point() {
    }

    public Point(float x, float y) {
        this.x = x;
        this.y = y;
    }

    public float getX() {
        return x;
    }

    public void setX(float x) {
        this.x = x;
    }

    public float getY() {
        return y;
    }

    public void setY(float y) {
        this.y = y;
    }
}
